export type GeneratedFile = {
  name: string;
  content: string;
  language: string;
};

export function generateProjectFiles(
  projectName: string,
  prompt: string
): GeneratedFile[] {
  const safeName =
    projectName.toLowerCase().replace(/[^a-z0-9]+/g, "-") ||
    "hexawave-project";

  const lower = prompt.toLowerCase();

  const isCRM =
    lower.includes("crm") ||
    lower.includes("customer") ||
    lower.includes("sales");

  const title = isCRM
    ? "CRM Dashboard"
    : projectName || "HexaWave App";

  const description = isCRM
    ? "Manage customers, leads, deals and sales activity."
    : prompt || "AI generated application.";

  return [
    {
      name: "app/page.tsx",
      language: "tsx",
      content: `"use client";

import { Activity, Users, TrendingUp, ArrowUpRight } from "lucide-react";

const stats = [
  { label: "Total Customers", value: "2,481", icon: Users },
  { label: "Active Deals", value: "184", icon: TrendingUp },
  { label: "Conversion", value: "24.8%", icon: Activity },
];

export default function Home() {
  return (
    <main className="min-h-screen bg-[#05070b] p-8 text-white">
      <div className="mx-auto max-w-6xl">
        <div className="mb-8">
          <p className="text-sm text-cyan-300">HexaWave Generated</p>
          <h1 className="mt-2 text-4xl font-bold">${title}</h1>
          <p className="mt-3 max-w-2xl text-white/40">
            ${description}
          </p>
        </div>

        <div className="grid gap-4 md:grid-cols-3">
          {stats.map((item) => {
            const Icon = item.icon;

            return (
              <div
                key={item.label}
                className="rounded-2xl border border-white/10 bg-white/[0.03] p-6"
              >
                <Icon className="text-cyan-300" size={20} />
                <div className="mt-5 text-3xl font-bold">
                  {item.value}
                </div>
                <div className="mt-1 text-sm text-white/35">
                  {item.label}
                </div>
              </div>
            );
          })}
        </div>

        <div className="mt-6 rounded-2xl border border-white/10 bg-white/[0.03] p-6">
          <div className="flex items-center justify-between">
            <h2 className="font-semibold">Recent Activity</h2>
            <ArrowUpRight size={17} className="text-white/30" />
          </div>

          <div className="mt-6 space-y-3">
            <div className="rounded-xl bg-white/[0.03] p-4 text-sm text-white/50">
              New customer added
            </div>

            <div className="rounded-xl bg-white/[0.03] p-4 text-sm text-white/50">
              Deal moved to qualified
            </div>

            <div className="rounded-xl bg-white/[0.03] p-4 text-sm text-white/50">
              Sales report generated
            </div>
          </div>
        </div>
      </div>
    </main>
  );
}`,
    },
    {
      name: "app/layout.tsx",
      language: "tsx",
      content: `import type { Metadata } from "next";

export const metadata: Metadata = {
  title: "${title}",
  description: "${description}",
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html lang="en">
      <body>{children}</body>
    </html>
  );
}`,
    },
    {
      name: "components/dashboard.tsx",
      language: "tsx",
      content: `export function Dashboard() {
  return (
    <section className="rounded-2xl border border-white/10 bg-white/[0.03] p-6">
      <h2 className="text-xl font-semibold">
        ${title}
      </h2>

      <p className="mt-2 text-sm text-white/40">
        Generated by HexaWave AI.
      </p>
    </section>
  );
}`,
    },
    {
      name: "README.md",
      language: "md",
      content: `# ${title}

Generated by HexaWave AI Software Factory.

## Project

${description}

## Project ID

${safeName}

## Getting Started

npm install
npm run dev
`,
    },
  ];
}
